'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const safety=require('../research-backup-safety-v83.js');
const fixture=JSON.parse(fs.readFileSync(process.argv[2],'utf8'));
assert.equal(Object.keys(fixture.owned).length,315);
assert(Object.values(fixture.owned).some(x=>x.owned===true&&x.rights===0));
const blank={owned:{},plans:[],homebreds:[],genomes:[],added:[],mareFavorites:{},mareGrades:{}};
const imported=safety.review(blank,fixture);
assert.equal(imported.ok,true);
assert.equal(Object.keys(imported.next.owned).length,315);
assert.deepEqual(imported.next.plans,[]);
assert.equal(imported.next.owned[Object.keys(fixture.owned)[0]].rights,fixture.owned[Object.keys(fixture.owned)[0]].rights);
const populated={...blank,owned:{localHorse:{owned:true,rights:3}},plans:[{id:'p1',title:'守るプラン'}],genomes:[{horse:'保存済み'}]};
const existing=JSON.stringify(populated);
const blocked=safety.review(populated,{...fixture,resetProductionData:true});
assert.equal(blocked.ok,false,'clean-start reset must not overwrite a non-empty device');
assert.equal(JSON.stringify(populated),existing,'backup review is read-only');
const compatible=safety.review(populated,{...fixture,resetProductionData:false,plans:[{id:'p1',title:'別PCの上書きプラン'},{id:'p2',title:'新規プラン'}]});
assert.equal(compatible.ok,true);
assert.equal(compatible.next.plans.length,2);
assert.equal(compatible.next.plans[0].title,'守るプラン','conflicted plan preserves local version');
assert.equal(compatible.next.genomes[0].horse,'保存済み');
assert.equal(compatible.next.owned.localHorse.rights,3);
assert(compatible.stats.conflicts.plans>0);
assert.equal(compatible.next.owned[Object.keys(fixture.owned)[0]].owned,true);
console.log('PASS v9.0.1: 315 fixture review; zero-right ownership; reset blocked for existing device; conflict-preserving merge; no source mutation.');
