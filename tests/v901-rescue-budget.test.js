'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const inv=require('../research-inverse-mild-v69.js');
const root=path.resolve(__dirname,'..');
assert(inv.shouldInspect90(0,0,100,60));
assert(inv.shouldInspect90(99,3,100,60));
assert(inv.shouldInspect90(100,2,100,60),'grade 2: reserve window must remain open');
assert(inv.shouldInspect90(159,0,100,60),'no complete candidate: reserve window must remain open');
assert(!inv.shouldInspect90(100,3,100,60),'grade 3: reserve is unnecessary');
assert(!inv.shouldInspect90(160,0,100,60),'hard budget must never be exceeded');
assert(!inv.shouldInspect90(-1,0,100,60));
const plans=[{id:'a',grade:2},{id:'b',grade:2}];
const selected=inv.retainStrongest90(plans,{id:'c',grade:3},2,x=>x.grade);
assert.deepEqual(selected.map(x=>x.id),['c','a']);
assert.deepEqual(plans.map(x=>x.id),['a','b'],'retention must not mutate prior shortlist');
assert.deepEqual(inv.retainStrongest90(plans,{id:'c',grade:3},0,x=>x.grade),[]);
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
assert(app.includes('if(!inv.shouldInspect90(recipeIndex,bestTheoryGrade,primaryLimit,rescueLimit))break;'));
assert(app.includes('theoryGrade<7||theoryGrade!==recipe.distinct'));
assert(app.includes('gameVerified:false'));
console.log('PASS v9.0.1 rescue budget: grade-2 does not prematurely halt grade-3 search; search cap; no mutation; explicit theory gate.');
